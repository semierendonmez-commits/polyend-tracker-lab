#!/usr/bin/env python3
"""Embed examples/scripts/*.lua into src/ws/examples_data.h (PLATFORM).

The firmware writes these to /Lab/PLATFORM/Scripts on a card that has no
Scripts folder yet (and on Launcher > F6 Examples). Run after editing an
example:  python3 tools/embed_scripts.py   (make lab-test checks they match).
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = sorted((root / "examples" / "scripts").glob("*.lua"))
out = root / "src" / "ws" / "examples_data.h"
lines = ["// Generated by tools/embed_scripts.py from examples/scripts/*.lua -- do not edit.",
         "#pragma once", "", "namespace plat {", "", "struct ExampleScript {",
         "    const char* file;", "    const char* text;", "};", "",
         "constexpr ExampleScript kExampleScripts[] = {"]
for p in src:
    text = p.read_text(encoding="ascii")
    if ")PLATLUA\"" in text:
        sys.exit(f"{p}: contains the raw-string delimiter")
    lines.append(f'    {{"{p.name}", R"PLATLUA({text})PLATLUA"}},')
lines += ["};", f"constexpr int kExampleScriptCount = {len(src)};", "", "}  // namespace plat", ""]
new = "\n".join(lines)
if len(sys.argv) > 1 and sys.argv[1] == "--check":
    sys.exit(0 if out.exists() and out.read_text() == new else "examples_data.h is stale: run tools/embed_scripts.py")
out.write_text(new)
print(f"wrote {out} ({len(src)} scripts, {sum(p.stat().st_size for p in src)} bytes)")
