#!/usr/bin/env python3
"""bin2c.py FILE SYMBOL OUT.c -- a byte array (8-aligned) + its size, for tests."""
import sys

data = open(sys.argv[1], "rb").read()
sym = sys.argv[2]
rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
with open(sys.argv[3], "w") as f:
    f.write(f"/* generated by tools/bin2c.py from {sys.argv[1].split('/')[-1]} */\n")
    f.write(f"__attribute__((aligned(8))) const unsigned char {sym}[] = {{\n" + ",\n".join(rows) + "\n};\n")
    f.write(f"const unsigned int {sym}Size = {len(data)}u;\n")
